"""Relational schema. PostgreSQL is the source of truth for what was sold.

Overselling is prevented by the conditional UPDATE in the worker; the CHECK
constraint and the partial unique index below are the last line of defence
if a code path ever got that wrong.
"""

import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    pass


class OrderStatus(enum.StrEnum):
    # PENDING only ever lives in Redis: the reservation is accepted and queued.
    PENDING = "PENDING"
    CONFIRMED = "CONFIRMED"
    REJECTED_SOLD_OUT = "REJECTED_SOLD_OUT"
    REJECTED_DUPLICATE = "REJECTED_DUPLICATE"
    FAILED = "FAILED"

    @property
    def is_terminal(self) -> bool:
        return self is not OrderStatus.PENDING


order_status_enum = Enum(
    OrderStatus,
    name="order_status",
    values_callable=lambda e: [m.value for m in e],
)


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    email: Mapped[str] = mapped_column(String(320), unique=True)
    password_hash: Mapped[str] = mapped_column(String(100))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Product(Base):
    __tablename__ = "products"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    sku: Mapped[str] = mapped_column(String(64), unique=True)
    name: Mapped[str] = mapped_column(String(200))
    description: Mapped[str] = mapped_column(Text, default="")
    price_cents: Mapped[int] = mapped_column(Integer)
    currency: Mapped[str] = mapped_column(String(3), default="INR")

    __table_args__ = (CheckConstraint("price_cents >= 0", name="ck_products_price_non_negative"),)


class Sale(Base):
    __tablename__ = "sales"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"))
    name: Mapped[str] = mapped_column(String(200))
    starts_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    ends_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    total_stock: Mapped[int] = mapped_column(Integer)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    product: Mapped[Product] = relationship(lazy="raise")
    inventory: Mapped["Inventory"] = relationship(back_populates="sale", lazy="raise")

    __table_args__ = (
        CheckConstraint("ends_at > starts_at", name="ck_sales_window"),
        CheckConstraint("total_stock >= 0", name="ck_sales_total_stock_non_negative"),
        Index("ix_sales_ends_at", "ends_at"),
    )


class Inventory(Base):
    """One hot row per sale. Only ever changed with a conditional, atomic UPDATE."""

    __tablename__ = "inventory"

    sale_id: Mapped[int] = mapped_column(
        ForeignKey("sales.id", ondelete="CASCADE"), primary_key=True
    )
    stock: Mapped[int] = mapped_column(Integer)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    sale: Mapped[Sale] = relationship(back_populates="inventory", lazy="raise")

    __table_args__ = (CheckConstraint("stock >= 0", name="ck_inventory_stock_non_negative"),)


class Order(Base):
    __tablename__ = "orders"

    # Generated by the API at reservation time, so redelivered queue messages
    # map onto the same primary key and processing stays idempotent.
    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    sale_id: Mapped[int] = mapped_column(ForeignKey("sales.id", ondelete="CASCADE"))
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    status: Mapped[OrderStatus] = mapped_column(order_status_enum)
    amount_cents: Mapped[int] = mapped_column(Integer)
    reserved_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    processed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    request_id: Mapped[str | None] = mapped_column(String(64), nullable=True)

    sale: Mapped[Sale] = relationship(lazy="raise")

    __table_args__ = (
        # At most one successful purchase per user per sale, enforced by the DB.
        Index(
            "uq_orders_one_confirmed_per_user",
            "sale_id",
            "user_id",
            unique=True,
            postgresql_where=text("status = 'CONFIRMED'"),
        ),
        Index("ix_orders_user_reserved_at", "user_id", "reserved_at"),
        Index("ix_orders_sale_status", "sale_id", "status"),
    )
