-- Atomically reserve one unit of flash-sale inventory for a user.
--
-- Redis executes a script as a single, uninterruptible unit on its one
-- command thread, so the check-and-decrement below cannot interleave with any
-- other request: two buyers can never both take the "last" unit. This is the
-- fix for the classic SELECT-then-UPDATE race that oversold 540/500.
--
-- All keys share the {sale_id} hash tag, so the script is Redis Cluster safe.
--
-- KEYS[1] sale:{id}:stock   integer  remaining reservable units
-- KEYS[2] sale:{id}:buyers  hash     user_id -> order_id
-- KEYS[3] sale:{id}:meta    hash     starts_at_ms, ends_at_ms
-- ARGV[1] user_id
-- ARGV[2] order_id (pre-generated by the API)
--
-- Returns {code, order_id, remaining}
--    1  RESERVED         new reservation, publish it
--    2  DUPLICATE        user already holds a reservation -> same order_id
--    0  SOLD_OUT
--   -1  NOT_INITIALISED  sale not primed in Redis yet
--   -2  NOT_STARTED
--   -3  ENDED

local stock = redis.call('GET', KEYS[1])
local starts = tonumber(redis.call('HGET', KEYS[3], 'starts_at_ms'))
local ends = tonumber(redis.call('HGET', KEYS[3], 'ends_at_ms'))
if (not stock) or (not starts) or (not ends) then
  return {-1, '', 0}
end
stock = tonumber(stock)

-- Idempotency: repeated clicks / retries resolve to the existing order.
local existing = redis.call('HGET', KEYS[2], ARGV[1])
if existing then
  return {2, existing, stock}
end

-- Use Redis' own clock so every API replica agrees on when the sale opens.
local t = redis.call('TIME')
local now_ms = tonumber(t[1]) * 1000 + math.floor(tonumber(t[2]) / 1000)
if now_ms < starts then
  return {-2, '', stock}
end
if now_ms >= ends then
  return {-3, '', stock}
end

if stock <= 0 then
  return {0, '', 0}
end

local remaining = redis.call('DECR', KEYS[1])
redis.call('HSET', KEYS[2], ARGV[1], ARGV[2])
return {1, ARGV[2], remaining}
